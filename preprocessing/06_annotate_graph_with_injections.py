def main():

    print()
    print("=" * 70)
    print(
        "SecureGAT-Agent Injection-aware AST Graph Annotation V2"
    )
    print("=" * 70)
    print()

    print(
        "Execution device: CPU"
    )

    print(
        "AST annotation strategy:",
        ANNOTATION_STRATEGY
    )

    print()

    # --------------------------------------------------------------
    # Create output
    # --------------------------------------------------------------

    os.makedirs(
        OUTPUT_ROOT,
        exist_ok=True
    )

    # --------------------------------------------------------------
    # Global counters
    # --------------------------------------------------------------

    total_graphs = 0
    total_injections = 0
    total_matched = 0
    total_unmatched = 0

    global_records = []

    global_report = {}

    # ==================================================================
    # Vulnerability loop
    # ==================================================================

    for vulnerability in VULNERABILITIES:

        print(
            vulnerability
        )

        print(
            "-" * 70
        )

        graph_dir = os.path.join(
            GRAPH_ROOT,
            vulnerability
        )

        output_dir = os.path.join(
            OUTPUT_ROOT,
            vulnerability
        )

        os.makedirs(
            output_dir,
            exist_ok=True
        )

        vulnerability_report = {

            "graphs": 0,

            "total_injections": 0,

            "matched_injections": 0,

            "unmatched_injections": 0,

            "total_positive_nodes": 0,

            "contracts": {}
        }

        if not os.path.isdir(
            graph_dir
        ):

            print(
                f"WARNING: graph directory does not exist: "
                f"{graph_dir}"
            )

            continue

        # --------------------------------------------------------------
        # Graph files
        # --------------------------------------------------------------

        graph_files = [

            filename

            for filename in os.listdir(
                graph_dir
            )

            if filename.endswith(".pt")
        ]

        graph_files.sort(
            key=lambda filename: (
                contract_number_from_graph(
                    filename
                )
                or 999999
            )
        )

        print(
            f"Contracts: {len(graph_files)}"
        )

        print()

        # ==============================================================
        # Contract loop
        # ==============================================================

        for graph_file in graph_files:

            contract_id = (
                contract_number_from_graph(
                    graph_file
                )
            )

            if contract_id is None:

                print(
                    "WARNING: Cannot determine contract ID:",
                    graph_file
                )

                continue

            graph_path = os.path.join(
                graph_dir,
                graph_file
            )

            # ----------------------------------------------------------
            # Load graph
            # ----------------------------------------------------------

            graph = torch.load(
                graph_path,
                map_location="cpu"
            )

            # ----------------------------------------------------------
            # Verify clean graph structure
            # ----------------------------------------------------------

            required_attributes = [

                "node_type_name",

                "node_start",

                "node_end",

                "parent_index"
            ]

            missing = [

                attribute

                for attribute in required_attributes

                if not hasattr(
                    graph,
                    attribute
                )
            ]

            if missing:

                raise RuntimeError(
                    f"Graph {graph_path} is missing required "
                    f"clean-AST attributes: {missing}"
                )

            # ----------------------------------------------------------
            # Load exact source
            # ----------------------------------------------------------

            source_bytes = load_source(
                vulnerability,
                contract_id
            )

            # ----------------------------------------------------------
            # Load exact BugLog
            # ----------------------------------------------------------

            injections = load_buglog(
                vulnerability,
                contract_id
            )

            # ----------------------------------------------------------
            # Annotate
            # ----------------------------------------------------------

            (
                matched,
                unmatched,
                injection_records
            ) = annotate_graph(
                graph,
                injections,
                source_bytes
            )

            # ----------------------------------------------------------
            # Save annotated graph
            # ----------------------------------------------------------

            output_path = os.path.join(
                output_dir,
                graph_file
            )

            torch.save(
                graph,
                output_path
            )

            # ----------------------------------------------------------
            # Positive node count
            # ----------------------------------------------------------

            positive_nodes = int(
                graph.injection_label.sum().item()
            )

            # ----------------------------------------------------------
            # Save records
            # ----------------------------------------------------------

            for record in injection_records:

                global_records.append({

                    "vulnerability":
                        vulnerability,

                    "contract_id":
                        contract_id,

                    "graph":
                        graph_file,

                    **record
                })

            # ----------------------------------------------------------
            # Update counters
            # ----------------------------------------------------------

            num_injections = len(
                injections
            )

            vulnerability_report[
                "graphs"
            ] += 1

            vulnerability_report[
                "total_injections"
            ] += num_injections

            vulnerability_report[
                "matched_injections"
            ] += matched

            vulnerability_report[
                "unmatched_injections"
            ] += unmatched

            vulnerability_report[
                "total_positive_nodes"
            ] += positive_nodes

            vulnerability_report[
                "contracts"
            ][str(contract_id)] = {

                "graph":
                    graph_file,

                "source":
                    f"buggy_{contract_id}.sol",

                "buglog":
                    f"BugLog_{contract_id}.csv",

                "nodes":
                    int(graph.num_nodes),

                "edges":
                    int(graph.edge_index.shape[1]),

                "injections":
                    num_injections,

                "matched":
                    matched,

                "unmatched":
                    unmatched,

                "positive_nodes":
                    positive_nodes,

                "matching_rate":
                    (
                        matched /
                        num_injections *
                        100
                    )
                    if num_injections
                    else 0.0
            }

            total_graphs += 1

            total_injections += (
                num_injections
            )

            total_matched += matched

            total_unmatched += unmatched

        # ==============================================================
        # Vulnerability summary
        # ==============================================================

        global_report[
            vulnerability
        ] = vulnerability_report

        vuln_total = (
            vulnerability_report[
                "total_injections"
            ]
        )

        vuln_matched = (
            vulnerability_report[
                "matched_injections"
            ]
        )

        vuln_unmatched = (
            vulnerability_report[
                "unmatched_injections"
            ]
        )

        vuln_positive = (
            vulnerability_report[
                "total_positive_nodes"
            ]
        )

        vuln_rate = (

            vuln_matched /
            vuln_total *
            100

        ) if vuln_total else 0.0

        print(
            f"Graphs: {vulnerability_report['graphs']}"
        )

        print(
            f"Injections: {vuln_total}"
        )

        print(
            f"Matched: {vuln_matched}"
        )

        print(
            f"Unmatched: {vuln_unmatched}"
        )

        print(
            f"Matching rate: {vuln_rate:.2f} %"
        )

        print(
            f"Positive nodes: {vuln_positive}"
        )

        print()

    # ==================================================================
    # Global statistics
    # ==================================================================

    global_rate = (

        total_matched /
        total_injections *
        100

    ) if total_injections else 0.0

    # --------------------------------------------------------------
    # Count positive nodes
    # --------------------------------------------------------------

    total_positive_nodes = 0
    total_nodes = 0

    for vulnerability in VULNERABILITIES:

        output_dir = os.path.join(
            OUTPUT_ROOT,
            vulnerability
        )

        if not os.path.isdir(
            output_dir
        ):
            continue

        for filename in os.listdir(
            output_dir
        ):

            if not filename.endswith(".pt"):
                continue

            path = os.path.join(
                output_dir,
                filename
            )

            graph = torch.load(
                path,
                map_location="cpu"
            )

            total_nodes += int(
                graph.num_nodes
            )

            total_positive_nodes += int(
                graph.injection_label.sum().item()
            )

    positive_ratio = (

        total_positive_nodes /
        total_nodes

    ) if total_nodes else 0.0

    # ==================================================================
    # Print summary
    # ==================================================================

    print("=" * 70)

    print(
        "STEP 06 ANNOTATION SUMMARY"
    )

    print("=" * 70)

    print(
        f"Graphs: {total_graphs}"
    )

    print(
        f"Total injections: {total_injections}"
    )

    print(
        f"Matched injections: {total_matched}"
    )

    print(
        f"Unmatched injections: {total_unmatched}"
    )

    print(
        f"Matching rate: {global_rate:.2f} %"
    )

    print(
        f"Total AST nodes: {total_nodes}"
    )

    print(
        f"Positive AST nodes: {total_positive_nodes}"
    )

    print(
        f"Positive-node ratio: {positive_ratio:.6f}"
    )

    # ==================================================================
    # Save injection audit
    # ==================================================================

    audit_path = os.path.join(
        OUTPUT_ROOT,
        "injection_audit.csv"
    )

    write_injection_audit(
        audit_path,
        global_records
    )

