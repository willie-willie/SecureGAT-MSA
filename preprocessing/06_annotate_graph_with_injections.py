def write_injection_audit(
    path,
    records
):
    """
    Write one row per BugLog injection.
    """

    fieldnames = [
        
        "vulnerability",
    
        "contract_id",
    
        "graph",
    
        "injection_id",
    
        "buglog_row",
    
        "loc",
    
        "length",
    
        "bug_type",
    
        "approach",
    
        "source_start",
    
        "source_end",
    
        "source_length",
    
        "matched",
    
        "selection_method",
    
        "contained_node_count",
    
        "matched_node_count",
    
        "matched_nodes",
    
        "node_types"        

       
    ]
    

    with open(
        path,
        "w",
        encoding="utf-8",
        newline=""
    ) as f:

        writer = csv.DictWriter(
            f,
            fieldnames=fieldnames
        )

        writer.writeheader()

        for record in records:

            row = dict(record)

            row["matched_nodes"] = json.dumps(
                record.get(
                    "matched_nodes",
                    []
                )
            )

            row["node_types"] = json.dumps(
                record.get(
                    "node_types",
                    {}
                ),
                sort_keys=True
            )

            writer.writerow(row)


