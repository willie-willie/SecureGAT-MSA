def normalize_bug_type(name):
    """
    Normalize SolidiFI BugLog vulnerability names.
    """

    if name is None:
        return ""

    name = str(name).strip()

    mapping = {
        "Re+AC0-erntrancy": "Re-entrancy",
        "Re-entrancy": "Re-entrancy",

        "Overflow-Underflow":
            "Overflow-Underflow",

        "Unchecked-Send":
            "Unchecked-Send",

        "Unhandled-Exceptions":
            "Unhandled-Exceptions",

        "Timestamp-Dependency":
            "Timestamp-Dependency",

        "TOD":
            "TOD",

        "tx.origin":
            "tx.origin",
    }

    return mapping.get(name, name)


# ======================================================================
# Contract ID
# ======================================================================

def contract_number_from_graph(filename):
    """
    buggy_1.pt -> 1
    buggy_25.pt -> 25
    """

    base = os.path.basename(filename)

    if not base.startswith("buggy_"):
        return None

    try:
        value = base[len("buggy_"):]
        value = value.split(".")[0]
        return int(value)
    except Exception:
        return None


# ======================================================================
# Load Solidity source
# ======================================================================

def load_source(vulnerability, contract_id):
    """
    Load the exact Solidity source corresponding to the graph.
    """

    path = os.path.join(
        BUG_ROOT,
        vulnerability,
        f"buggy_{contract_id}.sol"
    )

    if not os.path.exists(path):
        raise FileNotFoundError(
            f"Source file not found: {path}"
        )

    with open(path, "rb") as f:
        return f.read()


# ======================================================================
# Source line offsets
# ======================================================================

def build_line_offsets(source_bytes):
    """
    Build zero-based source-byte offsets.

    line_offsets[0] = byte offset of line 1
    line_offsets[1] = byte offset of line 2
    ...

    Solidity AST src offsets are byte-based for the AST used here.
    """

    offsets = [0]

    for i, byte in enumerate(source_bytes):

        if byte == 10:  # LF / newline
            offsets.append(i + 1)

    return offsets


# ======================================================================
# BugLog line range -> source byte interval
# ======================================================================

def injection_to_source_interval(
    loc,
    length,
    line_offsets,
    source_length
):
    """
    Convert:

        loc    = starting source line
        length = number of source lines

    into:

        [start_byte, end_byte)

    Example:

        loc=22
        length=8

    corresponds to lines:

        22 ... 29

    """

    try:
        loc = int(loc)
        length = int(length)
    except Exception:
        return None

    if loc < 1:
        return None

    if length < 1:
        return None

    start_line_index = loc - 1

    if start_line_index >= len(line_offsets):
        return None

    start_offset = line_offsets[
        start_line_index
    ]

    # End of the last included line.
    end_line_index = (
        start_line_index + length
    )

    if end_line_index < len(line_offsets):

        end_offset = line_offsets[
            end_line_index
        ]

    else:

        end_offset = source_length

    if end_offset <= start_offset:
        return None

    return (
        start_offset,
        end_offset
    )


# ======================================================================
# Load BugLog
# ======================================================================

def load_buglog(
    vulnerability,
    contract_id
):
    """
    Load exactly ONE BugLog.

    buggy_1.pt
        -> BugLog_1.csv

    buggy_2.pt
        -> BugLog_2.csv

    etc.
    """

    path = os.path.join(
        BUG_ROOT,
        vulnerability,
        f"BugLog_{contract_id}.csv"
    )

    injections = []

    if not os.path.exists(path):

        print(
            f"WARNING: BugLog not found: {path}"
        )

        return injections

    with open(
        path,
        "r",
        encoding="utf-8",
        newline=""
    ) as f:

        reader = csv.DictReader(f)

        for row_number, row in enumerate(
            reader,
            start=2
        ):

            try:

                loc = int(
                    str(row.get("loc", "")).strip()
                )

                length = int(
                    str(row.get("length", "")).strip()
                )

            except Exception:

                print(
                    f"WARNING: invalid BugLog row "
                    f"{path}:{row_number}"
                )

                continue

            bug_type = normalize_bug_type(
                row.get(
                    "bug type",
                    ""
                )
            )

            injections.append({

                "loc": loc,

                "length": length,

                "bug_type": bug_type,

                "approach":
                    row.get(
                        "approach",
                        ""
                    ),

                "buglog_row":
                    row_number
            })

    return injections


# ======================================================================
# Graph node interval
# ======================================================================

def get_node_interval(
    graph,
    node_index
):
    """
    Return:

        (start, end)

    or None.

    Clean Step 05 graphs contain:

        node_start
        node_end
    """

    if not hasattr(graph, "node_start"):
        return None

    if not hasattr(graph, "node_end"):
        return None

    try:

        start = int(
            graph.node_start[node_index].item()
        )

        end = int(
            graph.node_end[node_index].item()
        )

    except Exception:

        return None

    # -1 means no source mapping.
    if start < 0 or end < 0:
        return None

    if end <= start:
        return None

    return (
        start,
        end
    )


# ======================================================================
# Node type name
# ======================================================================

def get_node_type_name(
    graph,
    node_index
):
    """
    Retrieve the human-readable AST node type.
    """

    if hasattr(
        graph,
        "node_type_name"
    ):

        try:
            return str(
                graph.node_type_name[
                    node_index
                ]
            )
        except Exception:
            pass

    return "Unknown"


# ======================================================================
# Interval containment
# ======================================================================

def interval_contained(
    node_start,
    node_end,
    injection_start,
    injection_end
):
    """
    True when the complete AST node span is inside
    the BugLog injection span.
    """

    return (
        node_start >= injection_start
        and
        node_end <= injection_end
    )


# ======================================================================
# Interval overlap
# ======================================================================

def interval_overlap(
    node_start,
    node_end,
    injection_start,
    injection_end
):
    """
    Half-open interval overlap.
    """

    return (
        node_start < injection_end
        and
        node_end > injection_start
    )


# ======================================================================
# Node containment
# ======================================================================

def node_contains(
    outer_start,
    outer_end,
    inner_start,
    inner_end
):
    """
    Determine whether one AST node contains another.
    """

    return (
        outer_start <= inner_start
        and
        outer_end >= inner_end
        and
        (
            outer_start < inner_start
            or
            outer_end > inner_end
        )
    )


# ======================================================================
# Remove unnecessary ancestor nodes
# ======================================================================

def remove_redundant_ancestors(
    graph,
    candidate_indices
):
    """
    Given AST nodes inside an injection region, remove nodes that
    merely contain another selected node.

    This prevents:

        FunctionDefinition
            Block
                ExpressionStatement
                    FunctionCall

    from all being labeled simply because they are nested.

    The more specific AST nodes remain.

    Important:
    This operates ONLY on candidate nodes already inside the
    injection interval.
    """

    if not candidate_indices:
        return []

    intervals = {}

    for index in candidate_indices:

        interval = get_node_interval(
            graph,
            index
        )

        if interval is not None:

            intervals[index] = interval

    if not intervals:
        return []

    keep = []

    for index, (
        start,
        end
    ) in intervals.items():

        contains_other = False

        for other, (
            other_start,
            other_end
        ) in intervals.items():

            if other == index:
                continue

            if node_contains(
                start,
                end,
                other_start,
                other_end
            ):

                contains_other = True
                break

        if not contains_other:
            keep.append(index)

    return sorted(
        keep
    )


# ======================================================================
# Find nodes inside injection
# ======================================================================

def find_injection_nodes(
    graph,
    injection_start,
    injection_end
):
    """
    Main AST localization algorithm.

    Stage 1:
        Find AST nodes fully contained in the BugLog region.

    Stage 2:
        Remove redundant ancestors.

    Stage 3:
        If no contained node exists, use the smallest overlapping
        source-mapped AST nodes as a fallback.

    Returns:

        selected_nodes
        all_contained_nodes
        fallback_nodes
    """

    num_nodes = int(
        graph.num_nodes
    )

    contained = []

    overlapping = []

    for node_index in range(
        num_nodes
    ):

        interval = get_node_interval(
            graph,
            node_index
        )

        if interval is None:
            continue

        node_start, node_end = interval

        if interval_contained(
            node_start,
            node_end,
            injection_start,
            injection_end
        ):

            contained.append(
                node_index
            )

        elif interval_overlap(
            node_start,
            node_end,
            injection_start,
            injection_end
        ):

            overlapping.append(
                node_index
            )

    # --------------------------------------------------------------
    # Primary selection
    # --------------------------------------------------------------

    selected = remove_redundant_ancestors(
        graph,
        contained
    )

    # --------------------------------------------------------------
    # Fallback
    # --------------------------------------------------------------
    #
    # Sometimes an injection boundary cuts through an AST node.
    # In that situation there may be no completely contained node.
    #
    # Select the smallest overlapping AST nodes.
    #

    fallback = []

    if not selected:

        if overlapping:

            # Find minimum source span among overlaps.
            spans = []

            for index in overlapping:

                interval = get_node_interval(
                    graph,
                    index
                )

                if interval is None:
                    continue

                start, end = interval

                span = end - start

                spans.append(
                    (
                        span,
                        index
                    )
                )

            if spans:

                min_span = min(
                    span
                    for span, _
                    in spans
                )

                fallback = sorted(
                    index
                    for span, index
                    in spans
                    if span == min_span
                )

                selected = fallback

    return (
        selected,
        contained,
        fallback
    )


# ======================================================================
# Annotate ONE graph
# ======================================================================

def annotate_graph(
    graph,
    injections,
    source_bytes
):
    """
    Annotate one graph.

    New graph attributes:

        injection_label
        injection_id
        injection_count
        matched_injection_count
        unmatched_injection_count

    Additional metadata:

        injection_node_type
        injection_node_depth
    """

    num_nodes = int(
        graph.num_nodes
    )

    # --------------------------------------------------------------
    # Binary node label
    # --------------------------------------------------------------

    injection_label = torch.zeros(
        num_nodes,
        dtype=torch.long
    )

    # --------------------------------------------------------------
    # Injection ID
    # --------------------------------------------------------------

    injection_id = torch.full(
        (
            num_nodes,
        ),
        -1,
        dtype=torch.long
    )

    # --------------------------------------------------------------
    # Number of injections assigned to each node
    # --------------------------------------------------------------

    injection_count = torch.zeros(
        num_nodes,
        dtype=torch.long
    )

    # --------------------------------------------------------------
    # Build source line offsets
    # --------------------------------------------------------------

    line_offsets = build_line_offsets(
        source_bytes
    )

    source_length = len(
        source_bytes
    )

    matched_injections = 0
    unmatched_injections = 0

    injection_records = []

    # ==================================================================
    # Process each BugLog injection
    # ==================================================================

    for injection_index, injection in enumerate(
        injections
    ):

        loc = injection["loc"]
        length = injection["length"]

        interval = injection_to_source_interval(
            loc,
            length,
            line_offsets,
            source_length
        )

        # --------------------------------------------------------------
        # Invalid source interval
        # --------------------------------------------------------------

        if interval is None:

            unmatched_injections += 1

            injection_records.append({

                "injection_id":
                    injection_index,

                "buglog_row":
                    injection.get(
                        "buglog_row"
                    ),

                "loc":
                    loc,

                "length":
                    length,

                "bug_type":
                    injection.get(
                        "bug_type",
                        ""
                    ),

                "source_start":
                    None,

                "source_end":
                    None,

                "matched":
                    False,

                "selection_method":
                    "invalid_interval",

                "matched_nodes":
                    []
            })

            continue

        injection_start, injection_end = interval

        # --------------------------------------------------------------
        # Find AST nodes
        # --------------------------------------------------------------

        (
            selected_nodes,
            contained_nodes,
            fallback_nodes
        ) = find_injection_nodes(
            graph,
            injection_start,
            injection_end
        )

        # --------------------------------------------------------------
        # Match result
        # --------------------------------------------------------------

        if selected_nodes:

            matched_injections += 1

            if fallback_nodes:

                selection_method = (
                    "smallest_overlapping"
                )

            else:

                selection_method = (
                    "contained_innermost"
                )

            # ----------------------------------------------------------
            # Label selected nodes
            # ----------------------------------------------------------

            for node_index in selected_nodes:

                injection_label[
                    node_index
                ] = 1

                injection_count[
                    node_index
                ] += 1

                # Preserve first injection ID.
                if injection_id[
                    node_index
                ] == -1:

                    injection_id[
                        node_index
                    ] = injection_index

        else:

            matched_injections += 0
            unmatched_injections += 1

            selection_method = (
                "no_source_mapped_node"
            )

        # --------------------------------------------------------------
        # Node type information
        # --------------------------------------------------------------

        node_types = {}

        for node_index in selected_nodes:

            node_type = get_node_type_name(
                graph,
                node_index
            )

            node_types[node_type] = (
                node_types.get(
                    node_type,
                    0
                ) + 1
            )

        # --------------------------------------------------------------
        # Record
        # --------------------------------------------------------------

        injection_records.append({

            "injection_id":
                injection_index,

            "buglog_row":
                injection.get(
                    "buglog_row"
                ),

            "loc":
                loc,

            "length":
                length,

            "bug_type":
                injection.get(
                    "bug_type",
                    ""
                ),

            "approach":
                injection.get(
                    "approach",
                    ""
                ),

            "source_start":
                injection_start,

            "source_end":
                injection_end,

            "source_length":
                injection_end -
                injection_start,

            "matched":
                bool(selected_nodes),

            "selection_method":
                selection_method,

            "contained_node_count":
                len(contained_nodes),

            "matched_node_count":
                len(selected_nodes),

            "matched_nodes":
                selected_nodes,

            "node_types":
                node_types
        })

    # ==================================================================
    # Attach annotations
    # ==================================================================

    graph.injection_label = (
        injection_label
    )

    graph.injection_id = (
        injection_id
    )

    graph.injection_count = (
        injection_count
    )

    graph.num_injections = (
        len(injections)
    )

    graph.num_matched_injections = (
        matched_injections
    )

    graph.num_unmatched_injections = (
        unmatched_injections
    )

    graph.annotation_version = (
        "step06_v2_clean_ast"
    )

    graph.annotation_strategy = (
        ANNOTATION_STRATEGY
    )

    return (
        matched_injections,
        unmatched_injections,
        injection_records
    )


